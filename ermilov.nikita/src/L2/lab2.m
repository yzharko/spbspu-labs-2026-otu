close all;

syms s

% Записываем непосредственные значения звеньев (Одинаковы для всех)
W1 = 1 / (s + 1);
W2 = 2;
W3 = 5 / (s^2 + 3*s + 2);

% Записываем преобразованный вид передаточной функции
W_final = (W1*W2+W3) / (1 + W1*W2 + W2 - W2*W3);

% Получаем итоговый результат
simplify(W_final)
